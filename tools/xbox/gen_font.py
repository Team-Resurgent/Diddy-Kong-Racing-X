#!/usr/bin/env python3
"""Embed the settings menu's font in the program: Platform/xbox/fonts/Fredoka.ttf
(SIL Open Font License, Platform/xbox/fonts/OFL.txt) as a C array in
Platform/xbox/gen/menu_font.h, which Platform/xbox/dkr_overlay.c rasterises
with stb_truetype at the display's own resolution.

Run by setup.py and the test harness's build; rewritten only when the font
changes, so the build does not redo the file for nothing.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import xbconfig  # noqa: E402

ROOT = xbconfig.ROOT
FONT = os.path.join(ROOT, "Platform", "xbox", "fonts", "Fredoka.ttf")
OUT = os.path.join(ROOT, "Platform", "xbox", "gen", "menu_font.h")


def main():
    data = open(FONT, "rb").read()
    lines = ["// Generated by tools/xbox/gen_font.py from Platform/xbox/fonts/Fredoka.ttf",
             "// (SIL Open Font License 1.1, Platform/xbox/fonts/OFL.txt). Do not edit.",
             "static const unsigned char kMenuFontTtf[%d] = {" % len(data)]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join("%d" % b for b in data[i:i + 24]) + ",")
    lines.append("};")
    text = "\n".join(lines) + "\n"
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    if os.path.isfile(OUT) and open(OUT, encoding="ascii").read() == text:
        return
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    print("gen_font: %s (%d bytes of font)" % (os.path.relpath(OUT, ROOT), len(data)))


if __name__ == "__main__":
    main()
